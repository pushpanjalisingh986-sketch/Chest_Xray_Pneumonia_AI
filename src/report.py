import io
from PIL import Image
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image as RLImage, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(
    patient_id: str,
    prob: float,
    uncertainty: float,
    threshold: float,
    triage_status: str,
    overlay_img_pil: Image.Image
) -> bytes:
    """Compiles clinical diagnostic findings and Grad-CAM visuals into an in-memory PDF report."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    story = []
    styles = getSampleStyleSheet()

    # Title Header
    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=18, textColor=colors.HexColor('#0F172A'), spaceAfter=12)
    story.append(Paragraph("<b>CLINICAL RADIOLOGY AI SCREENING REPORT</b>", title_style))
    story.append(Spacer(1, 10))

    # Diagnostic Findings Summary Table
    data = [
        ["Patient Reference ID:", patient_id, "Operating Threshold (τ):", f"{threshold * 100:.1f}%"],
        ["Calibrated Risk Score:", f"{prob * 100:.2f}% ± {uncertainty * 100:.2f}%", "Triage Decision:", triage_status],
    ]
    t = Table(data, colWidths=[130, 140, 130, 140])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#0F172A')),
        ('FONTNAME', (0, 0), (-1, -1), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
    ]))
    story.append(t)
    story.append(Spacer(1, 15))

    # Embedded Grad-CAM Visual
    img_buf = io.BytesIO()
    overlay_img_pil.save(img_buf, format='PNG')
    img_buf.seek(0)
    story.append(RLImage(img_buf, width=300, height=300))
    story.append(Spacer(1, 15))

    # Clinical Disclaimer
    disc_style = ParagraphStyle('DiscStyle', parent=styles['Italic'], fontSize=8, textColor=colors.HexColor('#64748B'))
    story.append(Paragraph("<b>Clinical Notice:</b> This automated diagnostic summary is generated by a calibrated ResNet50 model with Monte Carlo uncertainty estimation. It is designed solely for radiologist queue prioritization and decision support.", disc_style))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes